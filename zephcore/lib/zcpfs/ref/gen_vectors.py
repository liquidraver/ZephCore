"""Generate ../vectors.json, the test vectors of SPEC.md section 15.

The handshake values are computed here step by step from the primitives and
then compared with what the model's functions return, so the file is checked
twice. Run without arguments to rewrite the file; `--check` compares only.
"""

import json
import os
import sys

import ascon
import zcpfs
from curve import edwards_to_montgomery, x25519, x25519_public
from zcpfs import (Drbg, Identity, Params, Session, auth, hs1_make, hs1_verify,
                   hs2_make, hs2_process, kdf, step, text_plaintext, with_hint)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "vectors.json")
P = Params()


def hx(b):
    return b.hex()


def seq(start, n):
    return bytes((start + i) & 0xFF for i in range(n))


def build():
    v = {"comment": "zcpfs test vectors, generated by ref/gen_vectors.py from SPEC.md "
                    "draft 0.8. All values are hex. Do not edit by hand."}

    # 1. KDF and AUTH -------------------------------------------------------
    v["kdf"] = [
        {"label": label, "parts": [hx(p) for p in parts], "n": n,
         "out": hx(kdf(label, *parts, n=n))}
        for label, parts, n in (
            ("step", [seq(0, 32)], 80),
            ("ack", [seq(0, 16), seq(0x80, 20)], 4),
            ("master", [seq(i * 16, 32) for i in range(8)], 32),
            ("probe", [seq(1, 32), seq(2, 32), seq(3, 32), seq(4, 4)], 32),
            ("drbg.gen", [seq(9, 32)], 48),
            ("hs1", [b""], 32),
        )]
    k = seq(0xA0, 32)
    v["auth"] = [{"k": hx(k), "ad": hx(ad), "tag": hx(auth(k, ad))}
                 for ad in (b"\x01" + seq(0, 32), b"\x03" + seq(0, 4), b"")]

    # 2. Generator ----------------------------------------------------------
    g = Drbg(seq(0x40, 32), seq(0x60, 32))
    gen = {"hw": hx(seq(0x40, 32)), "saved": hx(seq(0x60, 32)), "k0": hx(g.k), "steps": []}
    for n in (32, 4, 1):
        out = g.generate(n)
        gen["steps"].append({"op": "generate", "n": n, "out": hx(out), "k": hx(g.k)})
    g.mix(seq(0x70, 32))
    gen["steps"].append({"op": "mix", "x": hx(seq(0x70, 32)), "k": hx(g.k)})
    v["drbg"] = gen

    # 3. Handshake ----------------------------------------------------------
    i, r = Identity(seq(0x00, 32)), Identity(seq(0x20, 32))
    ss = i.shared_secret(r.S)
    drbg_i, drbg_r = Drbg(seq(0x40, 32)), Drbg(seq(0x50, 32))
    e_i = Drbg(seq(0x40, 32)).generate(32)
    e_r = Drbg(seq(0x50, 32)).generate(32)
    E_i, E_r = x25519_public(e_i), x25519_public(e_r)
    es = x25519(e_i, r.A)
    ee = x25519(e_i, E_r)
    se = x25519(i.a, E_r)
    k1 = kdf("hs1", ss, es, i.S, r.S, E_i, n=32)
    tag1 = auth(k1, b"\x01" + E_i)
    master = kdf("master", ss, es, ee, se, i.S, r.S, E_i, E_r, n=32)
    k2 = kdf("hs2", master, n=32)
    tag2 = auth(k2, b"\x02" + E_r)
    ck_i2r = kdf("chain.i2r", master, n=32)
    ck_r2i = kdf("chain.r2i", master, n=32)
    feed = kdf("drbg.feed", master, n=32)
    hdr_ir = bytes([r.S[0], i.S[0]])
    hdr_ri = bytes([i.S[0], r.S[0]])

    # the same through the model
    out, body1 = hs1_make(drbg_i, ss, i.S, r.S)
    assert body1 == E_i + tag1 and out.es == es
    assert hs1_verify(ss, r.a, i.S, r.S, body1) == es == x25519(r.a, E_i)
    made = hs2_make(drbg_r, ss, es, i.S, r.S, E_i)
    assert made == (E_r + tag2, ck_i2r, ck_r2i, feed)
    assert hs2_process(ss, out, i.a, i.S, r.S, made[0]) == (ck_i2r, ck_r2i, feed)
    assert ee == x25519(e_r, E_i) and se == x25519(e_r, i.A)

    v["handshake"] = {
        "initiator": {"scalar": hx(i.a), "ed25519_public": hx(i.S), "x25519_public": hx(i.A)},
        "responder": {"scalar": hx(r.a), "ed25519_public": hx(r.S), "x25519_public": hx(r.A)},
        "ss": hx(ss),
        "e_i": hx(e_i), "E_i": hx(E_i), "e_r": hx(e_r), "E_r": hx(E_r),
        "es": hx(es), "ee": hx(ee), "se": hx(se),
        "k1": hx(k1), "tag1": hx(tag1),
        "master": hx(master), "k2": hx(k2), "tag2": hx(tag2),
        "ck_i2r": hx(ck_i2r), "ck_r2i": hx(ck_r2i), "drbg_feed": hx(feed),
        "packet_handshake_1": hx(hdr_ir + body1),
        "packet_handshake_2": hx(hdr_ri + made[0]),
    }

    # 4. Session ------------------------------------------------------------
    def chain(ck, n):
        rows = []
        for _ in range(n):
            ck, key, nonce, ackk = step(ck)
            rows.append({"key": hx(key), "nonce": hx(nonce), "ackk": hx(ackk), "ck_after": hx(ck)})
        return rows

    def packets(sender_ck, hdr, texts):
        s = Session(ck_s=sender_ck, ck_r=bytes(32), t_start=0, t_last=0)
        ad = hdr + bytes([zcpfs.TXT])
        rows = []
        for n, (attempt, text) in enumerate(texts):
            plain = text_plaintext(1_700_000_000 + n, attempt, text)
            padded = plain + (b"\x00" if (len(plain) + 6) % 16 == 0 else b"")
            body, ack4 = s.seal(ad, padded, 0)
            rows.append({"plaintext": hx(plain), "sealed_plaintext": hx(padded), "ad": hx(ad),
                         "payload": hx(hdr + body), "ack4": hx(ack4)})
        return rows

    texts = [(0, b"k"), (0, b"hello world"), (1, b"12345"), (0, b""), (4, b"fifth attempt"),
             (0, b"x" * 26), (0, b"Vienna is in the clouds"), (2, b"omw"), (0, b"y" * 160),
             (0, b"last")]
    v["session"] = {
        "chain_i2r": chain(ck_i2r, 3),
        "i_to_r": packets(ck_i2r, hdr_ir, texts),
        "r_to_i": packets(ck_r2i, hdr_ri, texts),
        "confirmation": hx(hdr_ir + Session(ck_s=ck_i2r, ck_r=bytes(32), t_start=0, t_last=0)
                           .seal(hdr_ir + bytes([zcpfs.TXT]), b"", 0)[0]),
    }

    # 5. Loss and reordering ------------------------------------------------
    sender = Session(ck_s=ck_i2r, ck_r=bytes(32), t_start=0, t_last=0)
    ad = hdr_ir + bytes([zcpfs.TXT])
    sent = [sender.seal(ad, b"m%02d" % n, 0)[0] for n in range(P.W + 2)]
    receiver = Session(ck_s=bytes(32), ck_r=ck_i2r, t_start=0, t_last=0)
    order = []
    for n in (0, 3, 1, 2):
        got = receiver.open(ad, sent[n], 0, P)
        order.append({"position": n, "opens": got is not None,
                      "skipped_after": len(receiver.skipped), "fails_after": receiver.fails})
    far = Session(ck_s=bytes(32), ck_r=ck_i2r, t_start=0, t_last=0)
    v["window"] = {
        "W": P.W, "S": P.S, "ad": hx(ad),
        "bodies": [hx(b) for b in sent],
        "open_order": order,
        "position_W_opens": far.open(ad, sent[P.W], 0, P) is not None,
        "position_W_minus_1_opens": far.open(ad, sent[P.W - 1], 0, P) is not None,
    }

    # 6. Probe --------------------------------------------------------------
    nonce4 = seq(0xC0, 4)
    kp = kdf("probe", ss, i.S, r.S, nonce4, n=32)
    v["probe"] = {"nonce4": hx(nonce4), "kp": hx(kp),
                  "payload": hx(hdr_ir + nonce4 + auth(kp, b"\x03" + nonce4))}

    # 7. Negative cases -----------------------------------------------------
    s = Session(ck_s=ck_i2r, ck_r=bytes(32), t_start=0, t_last=0)
    body, _ = s.seal(ad, b"intact", 0)

    def opens(a, b):
        return Session(ck_s=bytes(32), ck_r=ck_i2r, t_start=0, t_last=0).open(a, b, 0, P) is not None

    flip = lambda b, at: bytes(x ^ (1 if n == at % len(b) else 0) for n, x in enumerate(b))
    replay = Session(ck_s=bytes(32), ck_r=ck_i2r, t_start=0, t_last=0)
    first = replay.open(ad, body, 0, P) is not None
    aligned = text_plaintext(1_700_000_000, 0, b"t" * 5)        # 10 bytes: 10 + 6 = 16
    v["negative"] = {
        "body": hx(body), "ad": hx(ad),
        "intact_opens": opens(ad, body),
        "flipped_ciphertext_opens": opens(ad, flip(body, 0)),
        "flipped_tag_opens": opens(ad, flip(body, -1)),
        "other_dst_opens": opens(bytes([ad[0] ^ 1, ad[1], ad[2]]), body),
        "replay": {"first_opens": first, "second_opens": replay.open(ad, body, 0, P) is not None},
        "low_order_ephemeral": {
            "E": hx(bytes(32)), "es": hx(x25519(r.a, bytes(32))),
            "handshake_1_accepted": hs1_verify(ss, r.a, i.S, r.S, bytes(40)) is not None},
        "alignment": {"plaintext": hx(aligned), "sealed_plaintext": hx(aligned + b"\x00"),
                      "rule": "(len(plaintext) + 6) % 16 == 0 -> append 00"},
    }

    # Section 17: channel ---------------------------------------------------
    secret = seq(0xD0, 16)
    n6 = seq(0xE0, 6)
    rows = []
    for ptype, plain in ((zcpfs.GRP_TXT, (1_700_000_000).to_bytes(4, "little") + b"\x00alice: hello channel"),
                         (zcpfs.GRP_TXT, (1_700_000_000).to_bytes(4, "little") + b"\x00" + b"t" * 15),
                         (zcpfs.GRP_DATA, seq(0, 9))):
        payload = zcpfs.chan_seal(secret, ptype, plain, n6)
        assert zcpfs.chan_open(secret, ptype, payload)[:len(plain)] == plain
        rows.append({"type": ptype, "plaintext": hx(plain), "payload": hx(payload)})
    kc = kdf("chan", zcpfs.chan_field(secret), n6, n=32)
    v["channel"] = {"secret": hx(secret), "secret_field": hx(zcpfs.chan_field(secret)),
                    "channel_hash": hx(zcpfs.chan_hash(secret)), "n6": hx(n6),
                    "key": hx(kc[:16]), "nonce": hx(kc[16:]), "packets": rows}

    # Section 18: stateless pairwise mode -----------------------------------
    pn6 = seq(0xE8, 6)
    kpair = kdf("pair", ss, i.S, r.S, pn6, n=32)
    rows = []
    for ptype, plain in ((zcpfs.REQ, seq(1, 4) + b"telemetry"), (zcpfs.RESPONSE, seq(1, 4) + b"ok"),
                         (zcpfs.PATH, seq(0x30, 7)), (zcpfs.REQ, seq(0, 26)), (zcpfs.REQ, seq(0, 4))):
        payload = zcpfs.pair_seal(ss, i.S, r.S, ptype, plain, pn6)
        opened = zcpfs.pair_open(ss, i.S, r.S, ptype, payload)
        assert opened[:len(plain)] == plain and not any(opened[len(plain):])
        rows.append({"type": ptype, "plaintext": hx(plain), "sealed_plaintext": hx(opened),
                     "payload": hx(payload)})
    v["pairwise"] = {"sender": hx(i.S), "receiver": hx(r.S), "n6": hx(pn6),
                     "key": hx(kpair[:16]), "nonce": hx(kpair[16:]), "packets": rows}

    # Section 19: login -----------------------------------------------------
    password = b"hunter2"
    stamp = (1_700_000_000).to_bytes(4, "little")
    y_c = Drbg(seq(0x41, 32)).generate(32)
    y_s = Drbg(seq(0x51, 32)).generate(32)
    gen_in = kdf("pake.gen", password, i.S, r.S, n=32)
    G = zcpfs.pake_generator(password, i.S, r.S)
    lout, lbody1 = zcpfs.pake1_make(Drbg(seq(0x41, 32)), ss, i.S, r.S, password, stamp)
    assert lout.y == y_c and lout.Y == x25519(y_c, G)
    lS, lY_c, lss, lplain = zcpfs.pake1_open(r.a, r.S, lbody1)
    assert (lS, lY_c, lss) == (i.S, lout.Y, ss)
    reply_plain = (1_700_000_001).to_bytes(4, "little") + b"admin"
    branch, lck_i2r, lck_r2i, _ = zcpfs.pake_branch_make(Drbg(seq(0x51, 32)), ss, i.S, r.S, lY_c,
                                                          password, reply_plain)
    Y_s = x25519(y_s, G)
    K = x25519(y_s, lY_c)
    assert branch[:32] == Y_s and K == x25519(y_c, Y_s)
    lmaster = kdf("pake.master", ss, K, i.S, r.S, lY_c, Y_s, n=32)
    assert kdf("chain.i2r", lmaster, n=32) == lck_i2r
    got = zcpfs.pake_branch_open(ss, lout, i.S, r.S, branch)
    assert got[:3] == (reply_plain, lck_i2r, lck_r2i)
    wrong = zcpfs.pake_branch_make(Drbg(seq(0x52, 32)), ss, i.S, r.S, lY_c, b"hunter3", reply_plain)[0]
    reply = zcpfs.pake_reply_pack([branch, wrong])
    v["login"] = {
        "client": hx(i.S), "server": hx(r.S), "password": hx(password),
        "generator_input": hx(gen_in), "generator": hx(G),
        "y_c": hx(y_c), "Y_c": hx(lout.Y), "y_s": hx(y_s), "Y_s": hx(Y_s), "K": hx(K),
        "k_pake1": hx(kdf("pake1", ss, i.S, r.S, lout.Y, n=32)),
        "login_plaintext": hx(stamp), "sealed_login_plaintext": hx(lplain),
        "packet_login": hx(bytes([r.S[0]]) + lbody1),
        "master": hx(lmaster), "k_pake2": hx(kdf("pake2", lmaster, n=32)),
        "reply_plaintext": hx(reply_plain),
        "branch_right_password": hx(branch), "branch_other_password": hx(wrong),
        "other_branch_opens": zcpfs.pake_branch_open(ss, lout, i.S, r.S, wrong) is not None,
        "packet_reply_two_branches": hx(hdr_ri + reply),
        "ck_i2r": hx(lck_i2r), "ck_r2i": hx(lck_r2i)}
    v["elligator"] = [{"in": hx(x), "out": hx(zcpfs.elligator2(x))}
                      for x in (seq(3, 32), bytes(32), b"\xff" * 32, gen_in)]

    # Sections 6.1 and 6.3 --------------------------------------------------
    v["advert_tag"] = [
        {"name_field": hx(f), "name": hx(zcpfs.parse_name_field(f)[0]),
         "version": zcpfs.parse_name_field(f)[1]}
        for f in (b"alice\x00", b"alice", b"alice\x00\x02", b"\x00")]
    v["hint"] = [
        {"timestamp": 1_700_000_000, "attempt": attempt, "text": hx(text),
         "legacy_plaintext": hx(with_hint(1_700_000_000, attempt, text)),
         "hint_present": zcpfs.parse_text(with_hint(1_700_000_000, attempt, text))[4]}
        for attempt, text in ((0, b"hi"), (4, b"hi"), (0, b"t" * 8), (0, b"t" * 9), (0, b"t" * 11),
                              (0, b"t" * 12))]
    return v


def main():
    text = json.dumps(build(), indent=1) + "\n"
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8", newline="") as f:
            same = f.read() == text
        print("vectors.json is up to date" if same else "vectors.json DIFFERS from the model")
        sys.exit(0 if same else 1)
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT), len(text), "bytes")


if __name__ == "__main__":
    main()
