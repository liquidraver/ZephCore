"""Turn ../vectors.json into the header the host tests of the C library
include.

Every value of vectors.json becomes one table row, named by its path in the
file ("handshake.ss", "session.i_to_r.3.payload"). A list also gets a row
"<path>.#" with its length. Run without arguments to rewrite the header;
`--check` compares only.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VECTORS = os.path.join(HERE, "..", "vectors.json")
OUT = os.path.join(HERE, "..", "..", "..", "..", "tests", "unit", "zcpfs_vectors.h")

TEXT_KEYS = {"label", "op", "rule"}      # strings that are not hex
SKIP_KEYS = {"comment"}


def c_bytes(hex_text):
    return '"' + "".join("\\x" + hex_text[i:i + 2] for i in range(0, len(hex_text), 2)) + '"'


def c_text(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def flatten(value, path, rows):
    key = path.rsplit(".", 1)[-1]
    if isinstance(value, dict):
        for k, v in value.items():
            if k not in SKIP_KEYS:
                flatten(v, path + "." + k if path else k, rows)
    elif isinstance(value, list):
        rows["num"].append((path + ".#", len(value)))
        for n, v in enumerate(value):
            flatten(v, "%s.%d" % (path, n), rows)
    elif isinstance(value, bool):
        rows["num"].append((path, int(value)))
    elif isinstance(value, int):
        rows["num"].append((path, value))
    elif key in TEXT_KEYS:
        rows["text"].append((path, value))
    else:
        bytes.fromhex(value)             # raises if a value is not hex
        rows["bytes"].append((path, value.lower()))


def build():
    with open(VECTORS, encoding="utf-8") as f:
        vectors = json.load(f)
    rows = {"bytes": [], "num": [], "text": []}
    flatten(vectors, "", rows)

    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by zephcore/lib/zcpfs/ref/gen_c_vectors.py from vectors.json.",
           "// Do not edit by hand.",
           "#pragma once",
           "",
           "struct ZcVecBytes { const char *path; const char *data; unsigned len; };",
           "struct ZcVecNum { const char *path; long long value; };",
           "struct ZcVecText { const char *path; const char *text; };",
           "",
           "static const ZcVecBytes ZC_VEC_BYTES[] = {"]
    out += ["    {%s, %s, %d}," % (c_text(p), c_bytes(v), len(v) // 2) for p, v in rows["bytes"]]
    out += ["};", "", "static const ZcVecNum ZC_VEC_NUMS[] = {"]
    out += ["    {%s, %d}," % (c_text(p), v) for p, v in rows["num"]]
    out += ["};", "", "static const ZcVecText ZC_VEC_TEXT[] = {"]
    out += ["    {%s, %s}," % (c_text(p), c_text(v)) for p, v in rows["text"]]
    out += ["};", ""]
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8", newline="") as f:
            same = f.read() == text
        print("zcpfs_vectors.h is up to date" if same else "zcpfs_vectors.h DIFFERS from vectors.json")
        sys.exit(0 if same else 1)
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT), len(text), "bytes")


if __name__ == "__main__":
    main()
