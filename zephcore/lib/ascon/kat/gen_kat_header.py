"""Turn the known-answer files next to this script into a C/C++ header of
tables, for a test that has no file access.

    python gen_kat_header.py <output.h>           write the header
    python gen_kat_header.py <output.h> --check   compare only

Without a path the header goes to tests/unit/ascon_kat.h of this repository.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "..", "..", "..", "tests", "unit", "ascon_kat.h")


def records(name):
    """The records of one known-answer file, each a dict of lower-case hex."""
    rows, row = [], {}
    with open(os.path.join(HERE, name), encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            key, _, value = line.partition("=")
            key, value = key.strip(), value.strip().lower()
            if key == "Count":
                row = {}
                rows.append(row)
            else:
                row[key] = value
    return rows


def c_bytes(hex_text):
    return '"' + "".join("\\x" + hex_text[i:i + 2] for i in range(0, len(hex_text), 2)) + '"'


def n(hex_text):
    return len(hex_text) // 2


def build():
    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by zephcore/lib/ascon/kat/gen_kat_header.py from the known-answer files",
           "// next to it (subsets of the official ascon-c files, CC0). Do not edit by hand.",
           "#pragma once",
           "",
           "struct AsconKatAead { const char *key, *nonce, *pt, *ad, *ct; unsigned pt_len, ad_len; };",
           "struct AsconKatXof { const char *msg, *z, *md; unsigned msg_len, z_len, md_len; };",
           "",
           "// Ascon-AEAD128; ct is ciphertext then tag.",
           "static const AsconKatAead ASCON_KAT_AEAD128[] = {"]
    out += ["    {%s, %s, %s, %s, %s, %d, %d}," % (
        c_bytes(r["Key"]), c_bytes(r["Nonce"]), c_bytes(r["PT"]), c_bytes(r["AD"]), c_bytes(r["CT"]),
        n(r["PT"]), n(r["AD"])) for r in records("aead.txt")]
    for title, table, name in (("Ascon-Hash256", "ASCON_KAT_HASH256", "hash.txt"),
                               ("Ascon-XOF128, 64 bytes of output", "ASCON_KAT_XOF128", "xof.txt"),
                               ("Ascon-CXOF128, 64 bytes of output", "ASCON_KAT_CXOF128", "cxof.txt")):
        out += ["};", "", "// %s." % title, "static const AsconKatXof %s[] = {" % table]
        out += ["    {%s, %s, %s, %d, %d, %d}," % (
            c_bytes(r["Msg"]), c_bytes(r.get("Z", "")), c_bytes(r["MD"]),
            n(r["Msg"]), n(r.get("Z", "")), n(r["MD"])) for r in records(name)]
    out += ["};", ""]
    return "\n".join(out)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    path = args[0] if args else DEFAULT_OUT
    text = build()
    if "--check" in sys.argv:
        with open(path, encoding="utf-8", newline="") as f:
            same = f.read() == text
        print("ascon_kat.h is up to date" if same else "ascon_kat.h DIFFERS from the known-answer files")
        sys.exit(0 if same else 1)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(path), len(text), "bytes")


if __name__ == "__main__":
    main()
